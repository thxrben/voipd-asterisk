// Registration retry policy. Asterisk's defaults give up permanently after
// a 403 (forbidden_retry_interval=0) or after 10 failed attempts — the main
// reason FreePBX trunks stayed down. These never give up; the supervisor in
// voipd escalates further if a registration stays down.
const (
	regRetryInterval   = 30
	regForbiddenRetry  = 60
	regFatalRetry      = 60
	regMaxRetries      = 1000000
	regExpiration      = 480
	trunkQualifyFreq   = 60
	extQualifyFreq     = 30
	defaultSIPPort     = 5060
	defaultTLSPort     = 5061
	defaultMaxContacts = 3
)

var objectID = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.+-]*$`)

// Render produces the content of pjsip_voipd.conf.
func Render(cfg engine.Config) ([]byte, error) {
	w := &writer{}
	w.comment("Generated by voipd. Do not edit; changes are overwritten.")

	renderTransports(w, cfg.Network)
	for _, t := range cfg.Trunks {
		renderTrunk(w, t)
	}
	for _, e := range cfg.Extensions {
		renderExtension(w, e)
	}
	if w.err != nil {
		return nil, w.err
	}
	return w.buf.Bytes(), nil
}

func hasCert(n engine.Network) bool { return n.TLSCertFile != "" && n.TLSKeyFile != "" }

// renderTransports always writes all six transports (UDP/TCP/TLS for IPv4
// and IPv6). PJSIP decides at startup, once, which transport types its DNS
// resolver supports; a transport added later by reload would never get
// NAPTR/SRV/A resolution. TLS works without a certificate for outbound
// connections; with one, phones can connect via TLS too.
func renderTransports(w *writer, n engine.Network) {
	sip, tls := n.SIPPort, n.TLSPort
	if sip == 0 {
		sip = defaultSIPPort
	}
	if tls == 0 {
		tls = defaultTLSPort
	}
	nat := func(v6 bool) []string {
		var kv []string
		for _, p := range n.LocalNets {
			kv = append(kv, "local_net", p.String())
		}
		if !v6 && n.ExternalV4.IsValid() {
			a := n.ExternalV4.String()
			kv = append(kv, "external_signaling_address", a, "external_media_address", a)
		}
		return kv
	}
	type tr struct {
		name, proto, bind string
		v6                bool
	}
	trs := []tr{
		{"transport-udp", "udp", fmt.Sprintf("0.0.0.0:%d", sip), false},
		{"transport-udp6", "udp", fmt.Sprintf("[::]:%d", sip), true},
		{"transport-tcp", "tcp", fmt.Sprintf("0.0.0.0:%d", sip), false},
		{"transport-tcp6", "tcp", fmt.Sprintf("[::]:%d", sip), true},
		{"transport-tls", "tls", fmt.Sprintf("0.0.0.0:%d", tls), false},
		{"transport-tls6", "tls", fmt.Sprintf("[::]:%d", tls), true},
	}
	for _, t := range trs {
		kv := []string{"type", "transport", "protocol", t.proto, "bind", t.bind, "allow_reload", "yes"}
		if t.proto == "tls" {
			kv = append(kv, "method", "tlsv1_2", "verify_server", "yes", "ca_list_path", "/etc/ssl/certs")
			if hasCert(n) {
				kv = append(kv, "cert_file", n.TLSCertFile, "priv_key_file", n.TLSKeyFile)
			}
		}
		w.section(t.name, append(kv, nat(t.v6)...)...)
	}
}

// transportFor picks the transport object for a trunk. For "auto" the
// supervisor may later switch families; v4 is the default since it is what
// most NAT setups expect.
func transportFor(proto, family string) string {
	if proto == "" {
		proto = "udp"
	}
	name := "transport-" + proto
	if family == "v6" {
		name += "6"
	}
	return name
}

func codecs(c []string) string {
	if len(c) == 0 {
		return "g722,alaw,ulaw"
	}
	return strings.Join(c, ",")
}

func renderTrunk(w *writer, t engine.Trunk) {
	w.checkID(t.Name)
	w.comment("trunk " + t.Name)
	transport := transportFor(t.Transport, t.AddressFamily)

	// sip: with transport parameter rather than sips:, so PJSIP still does
	// RFC 3263 (NAPTR/SRV) resolution on the bare domain.
	server := "sip:" + t.Registrar
	if t.Transport == "tls" || t.Transport == "tcp" {
		server += ";transport=" + t.Transport
	}
	domain := t.Registrar

	// Trunks authenticated by IP have no credentials; Asterisk rejects an
	// auth object without username, so leave auth out entirely.
	authID := ""
	if t.AuthUsername != "" {
		authID = "trunk-" + t.Name + "-auth"
		auth := []string{"type", "auth", "auth_type", "userpass", "username", t.AuthUsername, "password", t.AuthPassword}
		if t.Profile == "telekom" {
			auth = append(auth, "realm", hostOnly(domain))
		}
		w.section(authID, auth...)
	}

	for _, l := range t.Lines {
		w.checkID(l.ID)
		id := engine.LineEndpoint(t.Name, l.ID)
		user := l.SIPUser
		if user == "" {
			user = l.Number
		}

		aor := []string{"type", "aor", "contact", server}
		if t.Profile != "telekom" {
			// Telekom's edge does not reliably answer OPTIONS; registration
			// state is the health signal there.
			aor = append(aor, "qualify_frequency", strconv.Itoa(trunkQualifyFreq))
		}
		w.section(id, aor...)

		ep := []string{
			"type", "endpoint",
			"context", "from-trunk",
			"transport", transport,
			"disallow", "all", "allow", codecs(t.Codecs),
			"aors", id,
			"from_user", user,
			"from_domain", domain,
			"direct_media", "no",
			"rtp_symmetric", "yes",
			"force_rport", "yes",
			"rewrite_contact", "yes",
			"dtmf_mode", "rfc4733",
			"trust_id_inbound", "yes",
			"timers", "yes",
			"100rel", "yes",
			"rtp_ipv6", yesNo(t.AddressFamily == "v6"),
		}
		if authID != "" {
			ep = append(ep, "outbound_auth", authID)
		}
		if t.OutboundProxy != "" {
			ep = append(ep, "outbound_proxy", "sip:"+t.OutboundProxy+";lr")
		}
		if t.SRTP {
			ep = append(ep, "media_encryption", "sdes")
			ep = append(ep, mediasec(t)...)
		}
		w.section(id, ep...)

		if l.Register {
			reg := []string{
				"type", "registration",
				"server_uri", server,
				"client_uri", "sip:" + user + "@" + domain,
				"contact_user", user,
				"transport", transport,
				"retry_interval", strconv.Itoa(regRetryInterval),
				"forbidden_retry_interval", strconv.Itoa(regForbiddenRetry),
				"fatal_retry_interval", strconv.Itoa(regFatalRetry),
				"max_retries", strconv.Itoa(regMaxRetries),
				"auth_rejection_permanent", "no",
				"expiration", strconv.Itoa(cmp.Or(t.Expiration, regExpiration)),
				"line", "yes",
				"endpoint", id,
			}
			if authID != "" {
				reg = append(reg, "outbound_auth", authID)
			}
			if t.OutboundProxy != "" {
				reg = append(reg, "outbound_proxy", "sip:"+t.OutboundProxy+";lr")
			}
			if t.SRTP {
				reg = append(reg, mediasec(t)...)
			}
			w.section(id, reg...)
		}
	}
}

// mediasec returns the RFC 3329 security negotiation options Deutsche
// Telekom requires before it accepts SDES-SRTP. Other providers get none.
func mediasec(t engine.Trunk) []string {
	if t.Profile != "telekom" {
		return nil
	}
	return []string{"security_negotiation", "mediasec", "security_mechanisms", "sdes-srtp;mediasec"}
}

func renderExtension(w *writer, e engine.Extension) {
	w.checkID(e.Number)
	w.checkID(e.SIPUsername)
	for _, p := range engine.ReservedEndpointPrefixes {
		if strings.HasPrefix(e.SIPUsername, p) {
			w.fail(fmt.Errorf("extension %s: SIP username %q must not start with %q", e.Number, e.SIPUsername, p))
		}
	}
	id := engine.ExtensionEndpoint(e.SIPUsername)
	w.comment("extension " + e.Number)
	maxContacts := e.MaxContacts
	if maxContacts <= 0 {
		maxContacts = defaultMaxContacts
	}
	w.section(id,
		"type", "auth", "auth_type", "userpass", "username", e.SIPUsername, "password", e.SIPPassword)
	w.section(id,
		"type", "aor",
		"max_contacts", strconv.Itoa(maxContacts),
		"remove_existing", "yes",
		"remove_unavailable", "yes",
		"qualify_frequency", strconv.Itoa(extQualifyFreq))
	ep := []string{
		"type", "endpoint",
		"context", "from-internal",
		"disallow", "all", "allow", codecs(e.Codecs),
		"auth", id,
		"aors", id,
		"identify_by", "username,auth_username",
		"callerid", fmt.Sprintf("%q <%s>", e.Name, e.Number),
		"direct_media", "no",
		"rtp_symmetric", "yes",
		"force_rport", "yes",
		"rewrite_contact", "yes",
		"dtmf_mode", "rfc4733",
		"rtp_ipv6", "yes",
		"send_pai", "yes",
	}
	if e.SRTP {
		ep = append(ep, "media_encryption", "sdes")
	}
	w.section(id, ep...)
}

// hostOnly strips an optional :port from host[:port] or [v6]:port.
func hostOnly(hostport string) string {
	if h, _, err := net.SplitHostPort(hostport); err == nil {
		return h
	}
	return hostport
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

type writer struct {
	buf bytes.Buffer
	err error
}

func (w *writer) fail(err error) {
	if w.err == nil {
		w.err = err
	}
}

func (w *writer) checkID(id string) {
	if !objectID.MatchString(id) {
		w.fail(fmt.Errorf("invalid identifier %q: only letters, digits and _.+- allowed", id))
	}
}

func (w *writer) comment(s string) {
	fmt.Fprintf(&w.buf, "\n; %s\n", strings.ReplaceAll(s, "\n", " "))
}

// section writes [name] followed by key = value pairs. kv must have even length.
func (w *writer) section(name string, kv ...string) {
	w.checkID(name)
	fmt.Fprintf(&w.buf, "[%s]\n", name)
	for i := 0; i+1 < len(kv); i += 2 {
		v, err := escape(kv[i+1])
		if err != nil {
			w.fail(fmt.Errorf("[%s] %s: %w", name, kv[i], err))
			continue
		}
		fmt.Fprintf(&w.buf, "%s = %s\n", kv[i], v)
	}
	w.buf.WriteByte('\n')
}

// escape makes a value safe for an Asterisk config file: ';' would start a
// comment and newlines would allow injecting arbitrary sections. Asterisk
// only unescapes "\;", so other backslashes are kept literally (verified:
// "pa;ss\word" round-trips through "pjsip show auth").
func escape(v string) (string, error) {
	if strings.ContainsAny(v, "\r\n\x00") {
		return "", fmt.Errorf("value contains control characters")
	}
	if strings.Contains(v, `\;`) {
		return "", fmt.Errorf(`value contains "\;", which Asterisk cannot represent`)
	}
	return strings.ReplaceAll(v, ";", `\;`), nil
}
